namespace Vivutio\Bundle\PartnerBundle\Enum;

/** Whether a partner is offered for new business. */
enum PartnerStatusEnum: string
{
    case Active = 'active';
    case Archived = 'archived';

    public function label(): string
    {
        return match ($this) {
            self::Active => 'Active',
            self::Archived => 'Archived',
        };
    }
}
